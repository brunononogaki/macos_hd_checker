'use strict';
// Disco ejetado/desconectado no meio da verificação NÃO pode virar milhares de "erros de leitura".
const fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto');
process.env.HD_CHECKER_HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'hdvan-'));
process.env.HD_CHECKER_VOLUMES = path.join(process.env.HD_CHECKER_HOME, 'vols');
process.env.HD_CHECKER_NO_KEYCHAIN = '1';
process.env.HD_CHECKER_TEST_DELAY_MS = '25';
const vol = path.join(process.env.HD_CHECKER_VOLUMES, 'Fotos'); fs.mkdirSync(vol, { recursive: true });
const config = require('../src/core/config'), dbmod = require('../src/core/db');
const { executeJob } = require('../src/core/scanner');
let failed = 0; const ok = (n, c) => { console.log(c ? '  ✔' : '  ✘', n); if (!c) failed++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const jpg = (i) => Buffer.concat([Buffer.from([0xFF, 0xD8, 0xFF, 0xE0, 0, 16]), Buffer.from('JFIF\0\x01\x01\0\0\x01\0\x01\0\0'), Buffer.from([0xFF, 0xDA, 0, 8, 1, 1, 0, 0, 0x3F, 0]), Buffer.from(crypto.randomBytes(3000).map((b) => (b === 0xFF ? 0xFE : b | 1))), Buffer.from([0xFF, 0xD9])]);
const N = 80, name = (i) => `f${String(i).padStart(3, '0')}.jpg`;
for (let i = 0; i < N; i++) fs.writeFileSync(path.join(vol, name(i)), jpg(i));
const cfg = config.load(); const job = { ...config.newJob('Fotos'), slicePercent: 100, maxMinutes: 0 }; cfg.jobs = [job]; config.save(cfg);
const q = (sql, ...a) => { const db = dbmod.open(config.dbPath(config.load())); try { return db.prepare(sql).get(...a); } finally { db.close(); } };

(async () => {
  console.log('Disco some no meio da verificação');
  setTimeout(() => fs.renameSync(vol, vol + '_gone'), 400);
  const r1 = await executeJob({ job, cfg: config.load(), sendEmail: false });
  ok('execução termina como interrompida, com explicação', r1.status === 'stopped' && /desconectado ou ejetado/.test(r1.note || ''));
  ok('NENHUM "erro de leitura" foi gravado', q("SELECT COUNT(*) n FROM events WHERE kind='ilegivel'").n === 0);
  ok('nada foi marcado como "sumiu"', q("SELECT COUNT(*) n FROM events WHERE kind='missing'").n === 0);
  ok('parou antes de ler tudo', (q('SELECT COUNT(*) n FROM files WHERE hash IS NOT NULL').n) < N);
  fs.renameSync(vol + '_gone', vol);
  process.env.HD_CHECKER_TEST_DELAY_MS = '0';
  console.log('Disco volta: continua de onde parou');
  const r2 = await executeJob({ job, cfg: config.load(), sendEmail: false });
  ok('2ª execução conclui sem problemas', r2.status === 'ok' && r2.newIssues.length === 0);
  ok('todos os arquivos têm hash', q('SELECT COUNT(*) n FROM files WHERE hash IS NOT NULL').n === N);
  fs.rmSync(vol, { recursive: true, force: true }); fs.mkdirSync(vol, { recursive: true });
  console.log('Arquivos movidos/apagados durante a leitura (disco continua lá)');
  for (let i = 0; i < N; i++) fs.writeFileSync(path.join(vol, `g${String(i).padStart(3, '0')}.jpg`), jpg(i));
  const db0 = dbmod.open(config.dbPath(config.load())); db0.prepare('DELETE FROM files').run(); db0.prepare('DELETE FROM events').run(); db0.close();
  const g = (i) => path.join(vol, `g${String(i).padStart(3, '0')}.jpg`);
  setTimeout(() => { for (let i = 70; i < N; i++) try { fs.unlinkSync(g(i)); } catch (e) { /* ok */ } }, 300);
  const r3 = await executeJob({ job, cfg: config.load(), sendEmail: false });
  ok('não gera "erro de leitura" para arquivo que sumiu', q("SELECT COUNT(*) n FROM events WHERE kind='ilegivel'").n === 0);
  ok('a execução registra que arquivos sumiram durante a leitura', /movidos\/apagados/.test(r3.note || '') && r3.status !== 'error');
  console.log('Alarmes falsos antigos (ENOENT) são limpos sozinhos');
  const db = dbmod.open(config.dbPath(config.load()));
  const victim = db.prepare("SELECT id, path FROM files WHERE hash IS NOT NULL LIMIT 1").get();
  db.prepare("UPDATE files SET status='suspect' WHERE id=?").run(victim.id);
  db.prepare("INSERT INTO events (run_id,volume,path,kind,severity,detail,at) VALUES (1,'Fotos',?,'ilegivel','error','erro de leitura (ENOENT): ENOENT: no such file or directory, open x',?)").run(victim.path, Date.now());
  db.close();
  const r4 = await executeJob({ job, cfg: config.load(), sendEmail: false });
  ok('o alarme falso foi fechado', q("SELECT COUNT(*) n FROM events WHERE kind='ilegivel' AND resolved=0").n === 0);
  ok('o arquivo voltou a "ok"', q('SELECT status FROM files WHERE path=?', victim.path).status === 'ok');
  ok('a execução informa a limpeza', /alarme\(s\) falso\(s\)/.test(r4.note || ''));
  console.log(failed ? '\nFALHAS: ' + failed : '\nvanish OK');
  process.exit(failed ? 1 : 0);
})().catch((e) => { console.error('ERRO', e); process.exit(1); });
